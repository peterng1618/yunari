#!/usr/bin/env node
/**
 * `AGENTS.md`'s two numbers for a source file — 500 is a signal, 800 is a stop —
 * and nothing in the repo computed either (`vg-536`). This reports the set and
 * ratchets it: a tracked `src/web` file over the stop that the ceiling does not
 * name fails, and a file that has left the set (a split) is reported and never
 * required to be removed.
 *
 * **The cut is generated versus authored, not product versus test.** The stop
 * applies to tests — four of the largest entries are e2e specs — so a measure
 * that excluded them would not have seen its own rows. A file is *generated*
 * when its first five lines carry both a generation claim and a do-not-edit
 * notice, which is what `font-trios.generated.ts` carries and what
 * `src/web/scripts/generate-font-trios.mjs` emits. What that lets through is a
 * generated file whose generator emits no marker: it lands *in* the over-stop
 * set, visible, rather than being silently excluded by a filename convention
 * nothing enforces or by a list someone must maintain.
 *
 * The ceiling is `scripts/oversize-files.ceiling.json`, a JSON array of the
 * accepted over-stop paths. It is edited only to **accept** a breach: a breach
 * that is split clears the failure with no edit, because the path was never in
 * it. The 500 tier is a count in the report and never a set — a per-file list of
 * the signal tier would be the second backlog this replaces.
 *
 * Exit 0 = nothing over the stop that the ceiling does not name. Exit 1 = an
 * addition. Exit 2 = the ceiling cannot be read, or the run could not complete:
 * a ratchet that fails open on its own breakage reports green over an unchecked
 * tree, so this one does not.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const DEFAULT_CEILING = "scripts/oversize-files.ceiling.json";
/** `AGENTS.md`, *Code and files*: 500 is a signal and 800 is a stop. */
const SIGNAL = 500;
const STOP = 800;
const EXTENSIONS = /\.(ts|tsx|mjs|css)$/;
const EXCLUDED = /(^|\/)(dist|node_modules)\//;
const HEAD_LINES = 5;
const GENERATED = /@generated|generated by|code generated/i;
const DO_NOT_EDIT = /do not edit/i;

/** A ceiling this script cannot read: a finding, never a pass. */
class CeilingError extends Error {}

/** The tracked set, which is the row's method: an untracked file is not a finding. */
function trackedFiles(root) {
  return execFileSync("git", ["ls-files", "src/web"], {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  })
    .split("\n")
    .filter((rel) => rel !== "" && EXTENSIONS.test(rel) && !EXCLUDED.test(rel));
}

/** A trailing newline ends the last line rather than opening an empty one. */
function lineCount(text) {
  if (text === "") return 0;
  const newlines = (text.match(/\n/g) ?? []).length;
  return text.endsWith("\n") ? newlines : newlines + 1;
}

function isGenerated(text) {
  const head = text.replace(/\r\n/g, "\n").split("\n").slice(0, HEAD_LINES).join("\n");
  return GENERATED.test(head) && DO_NOT_EDIT.test(head);
}

function measure(root) {
  const over = [];
  let signal = 0;
  let generated = 0;
  let files = 0;
  for (const rel of trackedFiles(root)) {
    files += 1;
    const text = readFileSync(join(root, rel), "utf8");
    if (isGenerated(text)) {
      generated += 1;
      continue;
    }
    const lines = lineCount(text);
    if (lines > SIGNAL) signal += 1;
    if (lines > STOP) over.push({ rel, lines });
  }
  over.sort((a, b) => (a.rel < b.rel ? -1 : 1));
  return { over, signal, generated, files };
}

function readCeiling(path) {
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    throw new CeilingError(`${path}: ${error.code ?? error.message}`);
  }
  if (!Array.isArray(parsed) || parsed.some((rel) => typeof rel !== "string" || rel === "")) {
    throw new CeilingError(`${path}: the ceiling must be a JSON array of repo-relative paths`);
  }
  return new Set(parsed);
}

function report(measured, ceiling) {
  const { over, files, generated, signal } = measured;
  const added = over.filter((entry) => !ceiling.has(entry.rel));
  const gone = [...ceiling].filter((rel) => !over.some((entry) => entry.rel === rel)).sort();
  console.log(
    `oversize-files: ${files} tracked src/web file(s), ${generated} generated, ` +
      `${signal} past the ${SIGNAL} signal, ${over.length} over the ${STOP} stop`,
  );
  for (const { rel, lines } of over) {
    console.log(`${ceiling.has(rel) ? "  accepted" : "  NEW     "} ${String(lines).padStart(6)}  ${rel}`);
  }
  if (gone.length > 0) {
    console.log(
      `oversize-files: ${gone.length} ceiling entry(s) no longer over the stop — drop them in the commit that split the file`,
    );
    for (const rel of gone) console.log(`  split   ${rel}`);
  }
  console.log(`oversize-files: ${added.length} over the stop and not in the ceiling`);
  return added;
}

function main(argv) {
  const flag = (name, fallback) => {
    const at = argv.indexOf(name);
    return at === -1 ? fallback : resolve(argv[at + 1]);
  };
  const root = flag("--root", ROOT);
  const ceilingPath = flag("--ceiling", resolve(root, DEFAULT_CEILING));
  let ceiling;
  try {
    ceiling = readCeiling(ceilingPath);
  } catch (error) {
    if (!(error instanceof CeilingError)) throw error;
    console.error(`oversize-files: CEILING — ${error.message}`);
    process.exit(2);
  }
  const added = report(measure(root), ceiling);
  process.exit(added.length > 0 ? 1 : 0);
}

// --- self-test: a fixture git repo, so no case pins a live file --------------

const body = (count, tag = "const a = 1;") => `${Array.from({ length: count }, () => tag).join("\n")}\n`;
const MARKED = "// Generated by a test fixture. Do not edit by hand.\n";

function fixture(files, ceiling) {
  const dir = mkdtempSync(join(tmpdir(), "yunari-oversize-files-"));
  for (const [rel, text] of Object.entries(files)) {
    const path = join(dir, rel);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
  if (ceiling !== null) {
    writeFileSync(join(dir, "ceiling.json"), JSON.stringify(ceiling, null, 2));
  }
  execFileSync("git", ["init", "-q"], { cwd: dir, stdio: "ignore" });
  execFileSync("git", ["add", "-A"], { cwd: dir, stdio: "ignore" });
  return dir;
}

function run(root) {
  try {
    const stdout = execFileSync(
      process.execPath,
      [fileURLToPath(import.meta.url), "--root", root, "--ceiling", join(root, "ceiling.json")],
      { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
    );
    return { code: 0, out: stdout };
  } catch (error) {
    return { code: error.status ?? 1, out: `${error.stdout ?? ""}${error.stderr ?? ""}` };
  }
}

function selfTest() {
  const src = "src/web/packages/editor/src/pane.ts";
  const cases = [
    [
      "accepts a file over the stop that the ceiling names",
      { [src]: body(900) },
      [src],
      0,
      "1 over the 800 stop",
    ],
    [
      "fails on a file over the stop the ceiling does not name",
      { [src]: body(900) },
      [],
      1,
      "NEW",
    ],
    [
      "a file at the stop is not over it",
      { [src]: body(800) },
      [],
      0,
      "0 over the 800 stop",
    ],
    [
      "a ceiling entry no longer over the stop is reported and does not fail",
      { [src]: body(900) },
      [src, "src/web/packages/editor/src/gone.ts"],
      0,
      "no longer over the stop",
    ],
    [
      "a generated file is not counted",
      { [src]: MARKED + body(900) },
      [],
      0,
      "1 generated, 0 past",
    ],
    [
      "a stylesheet over the stop is counted",
      { "src/web/packages/editor/src/shell.css": body(900, "a { color: red }") },
      [],
      1,
      "shell.css",
    ],
    [
      "counts the signal tier without ratcheting it",
      { [src]: body(600) },
      [],
      0,
      "1 past the 500 signal",
    ],
    [
      "refuses a ceiling that is not a list of paths",
      { [src]: body(900) },
      {},
      2,
      "CEILING",
    ],
    [
      "refuses a missing ceiling rather than passing",
      { [src]: body(900) },
      null,
      2,
      "CEILING",
    ],
  ];
  let failed = 0;
  for (const [name, files, ceiling, expected, needle] of cases) {
    const dir = fixture(files, ceiling);
    try {
      const { code, out } = run(dir);
      const ok = code === expected && out.includes(needle);
      if (!ok) failed += 1;
      console.log(
        `${ok ? "ok  " : "FAIL"} ${name}${ok ? "" : ` (expected exit ${expected} and "${needle}", got exit ${code}: ${out.trim().split("\n").at(-1)})`}`,
      );
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }
  if (failed > 0) {
    console.error(`oversize-files self-test: ${failed} case(s) wrong`);
    process.exit(1);
  }
  console.log(`oversize-files self-test: all ${cases.length} cases behave`);
  process.exit(0);
}

try {
  if (process.argv.includes("--self-test")) selfTest();
  else main(process.argv.slice(2));
} catch (error) {
  // Not fail-open: this is a ratchet, and a crash is an unchecked tree rather
  // than a clean one. Exit 2 is the "cannot read" code, for the same reason.
  console.error(`oversize-files: not run — ${error.message}`);
  process.exit(2);
}
