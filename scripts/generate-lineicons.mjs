#!/usr/bin/env node
// Generates packages/host/src/assets/icons/lineicons.generated.ts from the
// `lineicons` devDependency. Manual: `npm run icons:generate`. No build and no
// test may invoke it — the output is committed, and the adapter's shape test is
// what catches a bad refresh.
//
// `lineicons@1.3.2` is the free set (MIT, no attribution required); its SVGs
// are copied as data. The package is dev-only: the host loads the generated
// module, never the package.
//
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC_WEB = path.join(ROOT, "src/web");
const ICON_DIR = path.join(
  SRC_WEB,
  "node_modules/lineicons/assets/svgs/regular",
);
const OUT = path.join(
  SRC_WEB,
  "packages/host/src/assets/icons/lineicons.generated.ts",
);
const VERSION = JSON.parse(
  await readFile(
    path.join(SRC_WEB, "node_modules/lineicons/package.json"),
    "utf8",
  ),
).version;

/** The file's markup, without a leading XML declaration or BOM. */
function markupOf(source) {
  return source
    .replace(/^﻿/, "")
    .replace(/^\s*<\?xml[^>]*\?>\s*/i, "")
    .trim();
}

const files = (await readdir(ICON_DIR))
  .filter((name) => name.endsWith(".svg"))
  .sort();

const icons = [];
for (const file of files) {
  const svg = markupOf(await readFile(path.join(ICON_DIR, file), "utf8"));
  if (!svg.startsWith("<svg")) {
    throw new Error(`${file} does not start with an <svg> root.`);
  }
  icons.push({ name: file.slice(0, -4), svg });
}

icons.sort((left, right) => left.name.localeCompare(right.name));

const file =
  `// Generated by scripts/generate-lineicons.mjs from lineicons ${VERSION} (MIT).\n` +
  "// Do not edit; run `npm run icons:generate`.\n" +
  "export const LINEICONS_ICONS: readonly { readonly name: string; readonly svg: string }[] = [\n" +
  icons
    .map(
      (icon) =>
        `  { name: ${JSON.stringify(icon.name)}, svg: ${JSON.stringify(icon.svg)} },`,
    )
    .join("\n") +
  "\n];\n";

await mkdir(path.dirname(OUT), { recursive: true });
await writeFile(OUT, file, "utf8");
console.log(
  `Wrote ${icons.length} icons from lineicons ${VERSION} to ${path.relative(ROOT, OUT)}.`,
);
